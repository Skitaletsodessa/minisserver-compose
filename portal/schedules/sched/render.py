"""Renders the Home Assistant configuration from the schedule data (ADR 2). Pure: snapshot in, files out.

Deterministic (same data -> same bytes, no timestamps), so a diff shows real changes only. Every generated item carries a
content hash in its alias ("[sch a1b2c3d4]"), and one fingerprint script carries the hash of the whole set: what HA
actually loaded can be compared with what was rendered by looking at the aliases alone.
"""
import json
import hashlib
from . import model

HEADER = "# GENERATED by portal-schedules (Task 27) - do not edit; change the schedule through the API / schedctl.\n"
DAYS = ["mon", "tue", "wed", "thu", "fri", "sat", "sun"]


# ── tiny YAML emitter (JSON scalars are valid YAML; no PyYAML in the image) ──

def _scalar(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return json.dumps(v)
    return json.dumps(v, ensure_ascii=True)


def emit(v, indent=0, in_list=False):
    pad = "  " * indent
    if isinstance(v, dict):
        if not v:
            return "{}"
        lines = []
        for i, (k, x) in enumerate(v.items()):
            lead = "" if (in_list and i == 0) else pad
            if isinstance(x, (dict, list)) and x:
                lines.append("%s%s:\n%s" % (lead, k, emit(x, indent + 1)))
            else:
                lines.append("%s%s: %s" % (lead, k, emit(x, indent + 1)))
        return "\n".join(lines)
    if isinstance(v, list):
        if not v:
            return "[]"
        lines = []
        for x in v:
            if isinstance(x, (dict, list)) and x:
                lines.append("%s- %s" % (pad, emit(x, indent + 1, in_list=True).lstrip()))
            else:
                lines.append("%s- %s" % (pad, emit(x, indent + 1)))
        return "\n".join(lines)
    return _scalar(v)


def _h8(obj):
    return hashlib.sha256(json.dumps(obj, sort_keys=True, separators=(",", ":")).encode()).hexdigest()[:8]


def _item(key, label, body):
    """body: dict without alias. Returns (item dict with alias first, hash)."""
    h = _h8(body)
    out = {}
    if "id" in body:
        out["id"] = body["id"]
    out["alias"] = "Sch %s [sch %s]" % (label, h)
    out.update({k: v for k, v in body.items() if k != "id"})
    return out, h


def _at(minutes):
    return "%02d:%02d:00" % (minutes // 60, minutes % 60)


def _weekday_cond(days):
    if len(days) == 7:
        return []
    return [{"condition": "time", "weekday": [DAYS[d - 1] for d in days]}]


def _skip_cond(skips):
    if not skips:
        return []
    lst = "[" + ", ".join("'%s'" % d for d in sorted(skips)) + "]"
    return [{"condition": "template", "value_template": "{{ now().date().isoformat() not in %s }}" % lst}]


def _plug_automations(e, rules, skips):
    t = e["ha_target"]
    items = []
    for r in rules:
        s, en = model.parse_hhmm(r["start"]), model.parse_hhmm(r["end"])
        cond = _weekday_cond(r["days"])
        items.append(_item(None, "%s %s ON %s" % (e["id"], r["id"], r["start"]), {
            "id": "sch_%s_%s_on" % (e["id"], r["id"]), "mode": "single",
            "trigger": [{"platform": "time", "at": _at(s)}],
            "condition": cond + _skip_cond(skips),
            "action": [{"service": "switch.turn_on", "target": {"entity_id": t}}]}))
        items.append(_item(None, "%s %s OFF %s" % (e["id"], r["id"], r["end"]), {
            "id": "sch_%s_%s_off" % (e["id"], r["id"]), "mode": "single",
            "trigger": [{"platform": "time", "at": _at(en)}],
            "condition": cond,
            "action": [{"service": "switch.turn_off", "target": {"entity_id": t}}]}))
    mx = e["guardrails"]["max_on_minutes"]
    items.append(_item(None, "%s fail-safe OFF after %d min" % (e["id"], mx), {
        # Stateless on purpose: a state trigger with `for:` keeps its timer inside the automation, and an automation reload (any
        # schedule edit) or an HA restart would silently reset it. Checking every minute whether the plug has been ON longer than the
        # limit needs no memory; after an HA restart the age counts from the restart (the restored state's last_changed), so a run can
        # be extended by at most one restart - and the start-up reconcile switches anything outside its window OFF anyway.
        "id": "sch_%s_failsafe" % e["id"], "mode": "single",
        "trigger": [{"platform": "time_pattern", "minutes": "/1"}],
        "condition": [{"condition": "state", "entity_id": t, "state": "on"},
                      {"condition": "template", "value_template": "{{ (now() - states.%s.last_changed).total_seconds() > %d }}" % (t, mx * 60)}],
        "action": [{"service": "switch.turn_off", "target": {"entity_id": t}},
                   {"service": "logbook.log", "data": {"name": "Sch fail-safe",
                    "message": "%s: ON for %d min (guardrail max_on_minutes), switched OFF" % (t, mx)}}]}))
    items.append(_item(None, "%s reconcile on reconnect" % e["id"], {
        "id": "sch_%s_reconnect" % e["id"],
        "trigger": [{"platform": "state", "entity_id": t, "from": "unavailable"}],
        "action": [{"service": "script.sch_reconcile_%s" % e["id"]}]}))
    return items


def _vacuum_automations(e, rules, skips):
    items = []
    for r in rules:
        action = {"action": "script.turn_on", "target": {"entity_id": e["ha_target"]}}
        if r.get("variables"):
            action["data"] = {"variables": dict(sorted(r["variables"].items()))}
        items.append(_item(None, "%s %s %s" % (e["id"], r["id"], r["start"]), {
            "id": "sch_%s_%s" % (e["id"], r["id"]), "mode": "single",
            "trigger": [{"platform": "time", "at": _at(model.parse_hhmm(r["start"]))}],
            "condition": _weekday_cond(r["days"]) + _skip_cond(skips),
            "action": [action]}))
    return items


def _reconcile_script(e, rules, skips):
    t = e["ha_target"]
    wins = []
    for r in rules:
        days = "[" + ", ".join(str(d) for d in r["days"]) + "]"
        wins.append("(dow in %s and t >= %d and t < %d)" % (days, model.parse_hhmm(r["start"]), model.parse_hhmm(r["end"])))
    cond = " or ".join(wins) if wins else "false"
    skip_lst = "[" + ", ".join("'%s'" % d for d in sorted(skips)) + "]"
    target = "{{ 'on' if (today not in %s and (%s)) else 'off' }}" % (skip_lst, cond)
    seq = [
        {"variables": {"t": "{{ now().hour * 60 + now().minute }}", "dow": "{{ now().isoweekday() }}",
                       "today": "{{ now().date().isoformat() }}", "target": target,
                       "cur": "{{ states('%s') }}" % t}},
        {"if": [{"condition": "template", "value_template": "{{ target == 'on' and cur not in ['on', 'unavailable'] }}"}],
         "then": [{"service": "switch.turn_on", "target": {"entity_id": t}},
                  {"service": "logbook.log", "data": {"name": "Reconcile", "message": "%s: {{ cur }} \u2192 ON (schedule window)" % e["id"]}}]},
        {"if": [{"condition": "template", "value_template": "{{ target == 'off' and cur == 'on' }}"}],
         "then": [{"service": "switch.turn_off", "target": {"entity_id": t}},
                  {"service": "logbook.log", "data": {"name": "Reconcile", "message": "%s: on \u2192 OFF (outside schedule window)" % e["id"]}}]},
    ]
    body = {"sequence": seq}
    return _item(None, "reconcile %s" % e["id"], body)


def render(snapshot):
    """snapshot: {"entities": [ {id, kind, ha_target, managed, guardrails, rules, skip_dates}, ... ]} (see store.snapshot).
    Returns {"files": {relative path: text}, "expected": {"automations": {id: alias}, "scripts": {key: alias}}, "set_hash": str}."""
    files, exp_a, exp_s = {}, {}, {}
    script_keys = []
    for e in snapshot["entities"]:
        if not e["managed"] or e["kind"] not in model.RENDERABLE_KINDS:
            continue
        rules, skips = e["rules"], set(e.get("skip_dates", ()))
        if e["kind"] == "plug":
            items = _plug_automations(e, rules, skips)
        else:
            items = _vacuum_automations(e, rules, skips)
        files["automations/sch_%s.yaml" % e["id"]] = HEADER + emit([it for it, _ in items]) + "\n"
        for it, h in items:
            exp_a[it["id"]] = it["alias"]
        if e["kind"] == "plug":
            it, h = _reconcile_script(e, rules, skips)
            key = "sch_reconcile_%s" % e["id"]
            script_keys.append(key)
            files["scripts/%s.yaml" % key] = HEADER + emit({key: it}) + "\n"
            exp_s[key] = it["alias"]
    if not any(p.startswith("automations/") for p in files):
        files["automations/sch_none.yaml"] = HEADER + "[]\n"
    all_seq = [{"service": "script.%s" % k} for k in script_keys] or [{"delay": {"seconds": 0}}]
    ra, _ = _item(None, "reconcile all managed plugs", {"sequence": all_seq})
    files["scripts/sch_reconcile_all.yaml"] = HEADER + emit({"sch_reconcile_all": ra}) + "\n"
    exp_s["sch_reconcile_all"] = ra["alias"]
    set_hash = _h8({"a": exp_a, "s": exp_s})
    fp = {"alias": "Sch fingerprint [sch %s]" % set_hash, "sequence": [{"delay": {"seconds": 0}}]}
    files["scripts/sch_fingerprint.yaml"] = HEADER + emit({"sch_fingerprint": fp}) + "\n"
    exp_s["sch_fingerprint"] = fp["alias"]
    return {"files": dict(sorted(files.items())), "expected": {"automations": dict(sorted(exp_a.items())), "scripts": dict(sorted(exp_s.items()))},
            "set_hash": set_hash}
