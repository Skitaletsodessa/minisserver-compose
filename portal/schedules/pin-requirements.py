"""Resolves requirements.in with pip's own resolver and writes requirements.txt with sha256 hashes (pip --require-hashes ready).
Usage: python pin-requirements.py requirements.in requirements.txt   (needs network; run in any venv with pip)"""
import json, subprocess, sys, tempfile, os
src, dst = sys.argv[1], sys.argv[2]
rep = os.path.join(tempfile.mkdtemp(), "report.json")
subprocess.check_call([sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--only-binary", ":all:",
                       "--quiet", "--report", rep, "-r", src])
data = json.load(open(rep))
lines = ["# Generated by pin-requirements.py from %s - do not edit by hand." % os.path.basename(src)]
for it in sorted(data["install"], key=lambda i: i["metadata"]["name"].lower()):
    name, ver = it["metadata"]["name"], it["metadata"]["version"]
    h = it["download_info"]["archive_info"]["hashes"]["sha256"]
    lines.append("%s==%s %s%s    --hash=sha256:%s" % (name, ver, chr(92), chr(10), h))
open(dst, "w").write("\n".join(lines) + "\n")
print("pinned %d packages" % len(data["install"]))
