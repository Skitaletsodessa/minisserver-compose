#!/usr/bin/env python3
"""Prints the door route matrix (ADR 0009 amendment "single app gate") as Markdown, generated from gw/door.py.   python3 tools/gen_door_matrix.py > docs/portal/door-matrix.md"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from gw import door  # noqa: E402

LABEL = {"none": "none (public or authenticates itself)", "app": "app credential (device token or app session; a web session is refused)", "-": ""}
LIMITS = {"login": "Caddy 5 / 5 min / IP; gateway: per address 20 failures / 15 min, per account growing delay", "session": "Caddy 60 / 5 min / IP",
          "update_manifest": "Caddy 60 / 5 min / IP", "update_apk": "Caddy 12 / 5 min / IP (shared by the phones behind one address)",
          "camera": "Caddy 120 / min / IP", "camera_snapshot": "Caddy 150 / min / IP; gateway 240 / 5 min / person+device",
          "camera_live": "Caddy 8 / 5 min / IP; gateway 6 / 10 min / person+device; at most 4 streams at once, 20 min each",
          "camera_clip": "Caddy 60 / 10 min / IP; gateway 60 / 10 min / person+device", "events": "Caddy 12 / min / IP (one long stream per app)",
          "default": "Caddy 900 / min / IP"}
print("# Door route matrix (generated by tools/gen_door_matrix.py from gw/door.py; do not edit by hand)\n")
print("%d routes: %d allowed with an app credential, %d allowed without one, %d denied. A route that is not listed is denied (default deny)." % (
    len(door.TABLE), sum(1 for e in door.TABLE if e[2] == "allow" and e[3] == "app"), sum(1 for e in door.TABLE if e[2] == "allow" and e[3] == "none"), sum(1 for e in door.TABLE if e[2] == "deny")))
print("\n## Limit classes\n\n| Class | Limit |\n|---|---|")
for k, v in LIMITS.items():
    print("| `%s` | %s |" % (k, v))
for title, pick in (("Allowed, no credential needed", lambda e: e[2] == "allow" and e[3] == "none"),
                    ("Allowed, app credential required", lambda e: e[2] == "allow" and e[3] == "app"),
                    ("Denied through the door (reachable only on the tailnet site)", lambda e: e[2] == "deny")):
    print("\n## %s\n\n| Method | Route | Credential at the door | Limit class |\n|---|---|---|---|" % title)
    for e in door.TABLE:
        if pick(e):
            print("| %s | `%s` | %s | %s |" % (e[0], e[1], LABEL[e[3]], "`%s`" % e[4] if e[4] != "-" else ""))
